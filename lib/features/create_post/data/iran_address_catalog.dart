  static String englishLabel(String value) => value
      .split('-')
      .where((word) => word.isNotEmpty)
      .map((word) => '${word[0].toUpperCase()}${word.substring(1)}')
      .join(' ');

  static String provinceKey(String value) {
    final query = normalize(value);
    for (final entry in provinces.entries) {
      if (normalize(entry.key) == query ||
          normalize(entry.value.englishName) == query) {
        return entry.key;
      }
    }
    return value;
  }

  static String provinceLabel(String value) {
    final province = provinces[provinceKey(value)];
    return province == null ? value : englishLabel(province.englishName);
  }

  static String cityKey(String value, String province) {
    final cities = provinces[provinceKey(province)]?.cities;
    if (cities == null) return value;
    final query = normalize(value);
    for (final entry in cities.entries) {
      if (normalize(entry.key) == query || normalize(entry.value) == query) {
        return entry.key;
      }
    }
    return value;
  }

  static String cityLabel(String value, String province) {
    final english =
        provinces[provinceKey(province)]?.cities[cityKey(value, province)];
    return english == null ? value : englishLabel(english);
  }

  static String normalize(String value) => value
      .toLowerCase()
      .replaceAll('ي', 'ی')
      .replaceAll('ك', 'ک')
      .replaceAll(RegExp(r'[\s\u200c_-]+'), '');
